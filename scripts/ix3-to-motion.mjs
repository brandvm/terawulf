// Generates src/modules/motion-spec.ts from docs/audit/ix3-spec.json, the
// IX3 interactions as Webflow publishes them (decoded 2026-10-09 from the
// site's webflow.achunk.*.js). The motion module replays them with GSAP, so
// the approved motion and timing carry over exactly.
//
//   node scripts/ix3-to-motion.mjs
//
// Load-triggered interactions (Home hero, page header) are left out: they
// run as CSS @keyframes in src/styles.css so first-screen content never
// waits for JavaScript.
import { readFileSync, writeFileSync } from 'node:fs';

const LOAD_IN_CSS = new Set(['i-22814008', 'i-c2567f92']);
// IX3's ease picker, by index (from the runtime's ease table).
const EASES = ['none', 'power1.in', 'power1.out', 'power1.inOut', 'power2.in', 'power2.out', 'power2.inOut', 'power3.in', 'power3.out', 'power3.inOut', 'power4.in', 'power4.out', 'power4.inOut', 'back.in', 'back.out', 'back.inOut', 'bounce.in', 'bounce.out', 'bounce.inOut', 'circ.in', 'circ.out', 'circ.inOut', 'elastic.in', 'elastic.out', 'elastic.inOut', 'expo.in', 'expo.out', 'expo.inOut', 'sine.in', 'sine.out', 'sine.inOut'];
const BP = { main: '(min-width: 992px)', medium: '(min-width: 768px) and (max-width: 991px)', small: '(min-width: 480px) and (max-width: 767px)', tiny: '(max-width: 479px)' };

const spec = JSON.parse(readFileSync(new URL('../docs/audit/ix3-spec.json', import.meta.url), 'utf8'));
const timelines = Object.fromEntries(spec.timelines.map((t) => [t.id, t]));

const sel = ([kind, value]) =>
  kind === 'wf:class' ? value.map((c) => '.' + c).join(', ') : kind === 'wf:attribute' ? value : null;

function ease(e) {
  if (e == null) return undefined;
  if (typeof e === 'number') return EASES[e];
  if (e.type === 'customEase') {
    // "M0,160 C x1,y1 x2,y2 160,0" in a 160 box, y down → cubic-bezier.
    const n = e.bezierCurve.match(/-?[\d.]+/g).map(Number);
    const p = (v) => +(v / 160).toFixed(4);
    return `cubic(${p(n[2])},${+(1 - n[3] / 160).toFixed(4)},${p(n[4])},${+(1 - n[5] / 160).toFixed(4)})`;
  }
  return undefined;
}

function target(t) {
  const [kind, value, opts = {}] = t;
  if (kind === 'wf:trigger-only') return { self: true };
  const out = { sel: sel([kind, value]) };
  if (opts.relationship === 'within') {
    const [fk, fv] = opts.filterBy;
    out.within = fk === 'wf:trigger-only' ? 'trigger' : sel([fk, fv]);
  }
  return out;
}

const pct = (v) => (typeof v === 'string' && /^-?[\d.]+%$/.test(v) ? v : v);
function props(p) {
  const from = {}, to = {};
  const add = (k, [a, b]) => {
    const key = k === 'backgroundColor' ? 'backgroundColor' : k;
    const conv = (v) => (k === 'opacity' && typeof v === 'string' ? parseFloat(v) / 100 : pct(v));
    if (a != null) from[key] = conv(a);
    if (b != null) to[key] = conv(b);
  };
  for (const [k, v] of Object.entries(p['wf:transform'] || {})) add(k, v);
  for (const [k, v] of Object.entries(p['wf:style'] || {})) add(k, v);
  return { from, to };
}

const out = [];
for (const i of spec.interactions) {
  if (i.deleted || LOAD_IN_CSS.has(i.id)) continue;
  const [type, cfg, trig] = i.triggers[0];
  if (type !== 'wf:scroll') throw new Error(`${i.id}: unsupported trigger ${type}`);
  const c = cfg.scrollTriggerConfig;
  const skip = (i.conditionalPlayback || [])
    .filter((x) => x.behavior === 'dont-animate')
    .flatMap((x) => x.breakpoints.map((b) => BP[b]));
  const actions = [];
  for (const tid of i.timelineIds) {
    for (const a of timelines[tid].actions) {
      const { from, to } = props(a.properties);
      const tm = a.timing || {};
      const act = { targets: a.targets.map(target), tt: a.tt ?? 2, from, to };
      if (tm.duration != null) act.duration = tm.duration;
      if (tm.position != null) act.position = tm.position;
      if (ease(tm.ease)) act.ease = ease(tm.ease);
      if (tm.stagger) act.stagger = tm.stagger;
      if (a.splitText) act.split = a.splitText;
      actions.push(act);
    }
  }
  out.push({
    id: i.id,
    pages: i.scope.type === 'pages' ? i.scope.value : undefined,
    trigger: sel(trig),
    start: c.start,
    end: c.end,
    scrub: c.scrub ?? undefined,
    clamp: c.clamp || undefined,
    toggle: [c.enter, c.leave, c.enterBack, c.leaveBack].join(' '),
    skip: skip.length ? skip : undefined,
    actions,
  });
}

const ts = `// GENERATED by scripts/ix3-to-motion.mjs from docs/audit/ix3-spec.json.
// Do not edit by hand: change the source and re-run the script.
import type { MotionSpec } from './motion';

export const MOTION: MotionSpec[] = ${JSON.stringify(out, null, 1)};
`;
writeFileSync(new URL('../src/modules/motion-spec.ts', import.meta.url), ts);
console.log(`motion-spec.ts: ${out.length} scroll interactions, ${out.reduce((n, x) => n + x.actions.length, 0)} actions`);
